// Helper to generate full curriculum grade with accurate statuses matching concluded count
export const createCourseDisciplines = (curso: string, concluidasCount: number): DisciplinaAluno[] => {
  const modules = courseCurriculumMap[curso] || [
    { nome: `${curso} - Fundamentos & Introdução`, cargaHoraria: 20 },
    { nome: `${curso} - Módulo Prático Essencial`, cargaHoraria: 25 },
    { nome: `${curso} - Práticas Avançadas & Exercícios`, cargaHoraria: 30 },
    { nome: `${curso} - Aplicações no Mercado & Projetos`, cargaHoraria: 25 },
    { nome: `${curso} - Projeto Integrador de Conclusão`, cargaHoraria: 20 },
  ];

  const safeConcluidas = Math.max(0, Math.min(modules.length - 1, concluidasCount));

  return modules.map((mod, idx) => {
    if (idx < safeConcluidas) {
      const month = Math.max(1, idx + 2).toString().padStart(2, '0');
      return {
        id: `d_${idx + 1}`,
        nome: mod.nome,
        cargaHoraria: mod.cargaHoraria,
        status: 'concluida' as const,
        nota: Number((7.8 + ((idx * 0.7) % 2.1)).toFixed(1)),
        frequenciaPercent: 85 + ((idx * 4) % 15),
        dataConclusao: `15/${month}/2026`,
      };
    } else if (idx === safeConcluidas) {
      return {
        id: `d_${idx + 1}`,
        nome: mod.nome,
        cargaHoraria: mod.cargaHoraria,
        status: 'em_andamento' as const,
        nota: 6.5,
        frequenciaPercent: 70,
      };
    } else {
      return {
        id: `d_${idx + 1}`,
        nome: mod.nome,
        cargaHoraria: mod.cargaHoraria,
        status: 'pendente' as const,
      };
    }
  });
};

