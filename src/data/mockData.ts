const getDisciplinaAtualForCurso = (curso: string) => {
  if (curso.includes('Word')) return 'Word 2019 - Mala Direta & Normas ABNT';
  if (curso.includes('Excel')) return 'Excel 2019 - Fórmulas Avançadas & Dashboards';
  if (curso.includes('PowerPoint')) return 'PowerPoint 2019 - Apresentações Interativas & Animações';
  if (curso.includes('Windows')) return 'Windows 10 - Gerenciamento de Pastas & Segurança';
  if (curso.includes('Kids')) return 'Informática Kids - Lógica & Jogos Educativos';
  if (curso.includes('Hardware') || curso.includes('Redes')) return 'Hardware - Montagem, Manutenção & Redes Locais';
  if (curso.includes('Gestão')) return 'Gestão Empresarial - Atendimento & Processos Administrativos';
  if (curso.includes('Web') || curso.includes('Fullstack')) return 'Desenvolvimento Web - JavaScript ES6 & React';
  if (curso.includes('Design')) return 'Design Gráfico - Photoshop & Illustrator Vetorial';
  if (curso.includes('Farmácia')) return 'Atendente de Farmácia - Farmacologia & Primeiros Socorros';
  if (curso.includes('Robótica')) return 'Robótica Educacional - Programação em Arduino & Sensores';
  return `${curso} - Módulo Prático`;
};

